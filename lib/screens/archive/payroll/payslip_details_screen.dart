import 'package:flutter/material.dart';
import 'package:hive_ce_flutter/hive_ce_flutter.dart';
import 'package:intl/intl.dart';
import 'package:pdf/widgets.dart' as pw;
import 'package:printing/printing.dart';

import '../../../models/models.dart';
import '../../../services/boxes.dart';

class PayslipDetailsScreen extends StatelessWidget {
  const PayslipDetailsScreen({super.key, required this.payslipId});

  final String payslipId;

  String _money(int paise) =>
      NumberFormat.simpleCurrency(locale: 'en_IN').format(paise / 100);

  Future<void> _printPayslip(
    Payslip slip,
    Employee employee,
    PayrollRun run,
  ) async {
    final dateFormat = DateFormat('dd MMM yyyy');
    final document = pw.Document();
    document.addPage(
      pw.Page(
        build: (context) => pw.Padding(
          padding: const pw.EdgeInsets.all(28),
          child: pw.Column(
            crossAxisAlignment: pw.CrossAxisAlignment.start,
            children: [
              pw.Text(
                'BILLIT · PAYSLIP',
                style: pw.TextStyle(
                  fontSize: 22,
                  fontWeight: pw.FontWeight.bold,
                ),
              ),
              pw.SizedBox(height: 18),
              pw.Text('Employee: ${employee.name}'),
              pw.Text('Employee code: ${employee.employeeCode.isEmpty ? '—' : employee.employeeCode}'),
              pw.Text(
                'Period: ${dateFormat.format(run.periodStart)} – '
                '${dateFormat.format(run.periodEnd)}',
              ),
              pw.Text('Payslip reference: ${slip.id}'),
              pw.SizedBox(height: 22),
              pw.Table(
                border: pw.TableBorder.all(color: pw.PdfColors.grey400),
                children: [
                  _row('Basic pay', _money(slip.basePaise)),
                  _row('Allowances', _money(slip.allowancesPaise)),
                  _row('Gross pay', _money(slip.grossPaise)),
                  _row('Deductions', '- ${_money(slip.deductionsPaise)}'),
                  _row('Net pay', _money(slip.netPaise), bold: true),
                  _row('Paid', _money(slip.paidPaise)),
                  _row('Outstanding', _money(slip.outstandingPaise), bold: true),
                ],
              ),
              pw.SizedBox(height: 14),
              if (slip.payType == 'daily')
                pw.Text('Payable attendance days: ${slip.payableDays}'),
              pw.Text('Status: ${slip.status.toUpperCase()}'),
              pw.Spacer(),
              pw.Text(
                'This payslip was generated by Billit. '
                'Retain it for your records.',
                style: const pw.TextStyle(fontSize: 9),
              ),
            ],
          ),
        ),
      ),
    );
    await Printing.layoutPdf(onLayout: (_) async => document.save());
  }

  pw.TableRow _row(String label, String value, {bool bold = false}) {
    final style = pw.TextStyle(
      fontWeight: bold ? pw.FontWeight.bold : pw.FontWeight.normal,
    );
    return pw.TableRow(
      children: [
        pw.Padding(
          padding: const pw.EdgeInsets.all(8),
          child: pw.Text(label, style: style),
        ),
        pw.Padding(
          padding: const pw.EdgeInsets.all(8),
          child: pw.Align(
            alignment: pw.Alignment.centerRight,
            child: pw.Text(value, style: style),
          ),
        ),
      ],
    );
  }

  @override
  Widget build(BuildContext context) {
    final slipsBox = Hive.box<Payslip>(Boxes.payslips);
    return ValueListenableBuilder<Box<Payslip>>(
      valueListenable: slipsBox.listenable(keys: [payslipId]),
      builder: (context, box, _) {
        final slip = box.get(payslipId);
        if (slip == null) {
          return Scaffold(
            appBar: AppBar(title: const Text('Payslip')),
            body: const Center(child: Text('Payslip not found.')),
          );
        }
        final employee = Hive.box<Employee>(Boxes.employees).get(slip.employeeId);
        final run = Hive.box<PayrollRun>(Boxes.payrollRuns).get(slip.payrollRunId);
        if (employee == null || run == null) {
          return Scaffold(
            appBar: AppBar(title: const Text('Payslip')),
            body: const Center(
              child: Text('Employee or payroll period is missing.'),
            ),
          );
        }
        final dateFormat = DateFormat('dd MMM yyyy');
        return Scaffold(
          appBar: AppBar(
            title: const Text('Payslip'),
            actions: [
              IconButton(
                tooltip: 'Print or save PDF',
                onPressed: () => _printPayslip(slip, employee, run),
                icon: const Icon(Icons.picture_as_pdf_outlined),
              ),
            ],
          ),
          body: ListView(
            padding: const EdgeInsets.all(20),
            children: [
              Text(
                employee.name,
                style: Theme.of(context).textTheme.headlineSmall,
              ),
              Text(
                '${run.periodStart.month.toString().padLeft(2, '0')}/'
                '${run.periodStart.year} · ${slip.status.toUpperCase()}',
              ),
              if (employee.employeeCode.isNotEmpty)
                Text('Employee code: ${employee.employeeCode}'),
              if (employee.designation.isNotEmpty)
                Text('Designation: ${employee.designation}'),
              Text(
                '${dateFormat.format(run.periodStart)} – '
                '${dateFormat.format(run.periodEnd)}',
              ),
              const SizedBox(height: 20),
              Card(
                child: Padding(
                  padding: const EdgeInsets.all(16),
                  child: Column(
                    children: [
                      _line(context, 'Basic pay', slip.basePaise),
                      _line(context, 'Allowances', slip.allowancesPaise),
                      _line(context, 'Gross pay', slip.grossPaise, bold: true),
                      _line(context, 'Deductions', -slip.deductionsPaise),
                      const Divider(height: 24),
                      _line(context, 'Net pay', slip.netPaise, bold: true),
                      _line(context, 'Paid', slip.paidPaise),
                      _line(
                        context,
                        'Outstanding',
                        slip.outstandingPaise,
                        bold: true,
                      ),
                    ],
                  ),
                ),
              ),
              if (slip.payType == 'daily')
                Padding(
                  padding: const EdgeInsets.only(top: 12),
                  child: Text('Payable days: ${slip.payableDays}'),
                ),
              const SizedBox(height: 12),
              FilledButton.icon(
                onPressed: () => _printPayslip(slip, employee, run),
                icon: const Icon(Icons.picture_as_pdf_outlined),
                label: const Text('Print / save PDF'),
              ),
            ],
          ),
        );
      },
    );
  }

  Widget _line(
    BuildContext context,
    String label,
    int paise, {
    bool bold = false,
  }) {
    final style = Theme.of(context).textTheme.bodyLarge?.copyWith(
          fontWeight: bold ? FontWeight.w800 : FontWeight.normal,
        );
    return Padding(
      padding: const EdgeInsets.symmetric(vertical: 7),
      child: Row(
        children: [
          Expanded(child: Text(label, style: style)),
          Text(_money(paise), style: style),
        ],
      ),
    );
  }
}
